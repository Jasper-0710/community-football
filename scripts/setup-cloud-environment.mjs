import fs from 'node:fs/promises'
import { cloudEnvironment, loadCloudEnvironment, projectRoot, validateCloudEnvironment } from './cloud-environment.mjs'

const args = process.argv.slice(2)
if (args.length && (args.length !== 2 || args[0] !== '--admin-url')) throw new Error('用法：npm run cloud:setup [-- --admin-url <客户环境HTTPS地址>]')
if (args.length) {
  const url = new URL(args[1])
  if (url.protocol !== 'https:' || !url.hostname.startsWith(`${cloudEnvironment.envId}-`) || !url.hostname.endsWith('.app.tcloudbase.com')) throw new Error('请提供客户环境控制台生成的完整HTTPS访问地址。')
  const target = validateCloudEnvironment({ VITE_ADMIN_API_URL: args[1], VITE_COMPETITION_API_URL: args[1] }, { ...cloudEnvironment, adminApiUrl: '' })
  // Read back the exact route before persisting it; a domain existing is insufficient.
  const response = await fetch(target.adminApiUrl, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'http://127.0.0.1:5174' }, body: JSON.stringify({ action: 'competitions.listPublic' }), signal: AbortSignal.timeout(20_000), redirect: 'error' })
  const body = await response.json()
  if (!response.ok || body?.ok !== true || !Array.isArray(body.competitions) || response.headers.get('access-control-allow-origin') !== 'http://127.0.0.1:5174') throw new Error('客户HTTP地址未通过公开赛事及后台跨域验证，配置未保存。请检查路由是否关联 adminAuth。')
  cloudEnvironment.adminApiUrl = target.adminApiUrl
  await fs.writeFile(new URL('../config/cloud-environment.json', import.meta.url), JSON.stringify(cloudEnvironment, null, 2) + '\n')
}
const header = '# Generated by npm run cloud:setup; customer environment only. No secrets.\n'
await fs.writeFile(`${projectRoot}.env.local`, `${header}VITE_WECHAT_CLOUD_ENV_ID=${cloudEnvironment.envId}\nVITE_COMPETITION_API_URL=${cloudEnvironment.adminApiUrl}\n`)
await fs.writeFile(`${projectRoot}.env.admin.local`, `${header}VITE_WECHAT_CLOUD_ENV_ID=${cloudEnvironment.envId}\nVITE_ADMIN_API_URL=${cloudEnvironment.adminApiUrl}\n`)
for (const mode of ['development', 'production', 'admin']) loadCloudEnvironment(mode)
console.log(`已统一客户环境：${cloudEnvironment.envId}（AppID ${cloudEnvironment.appid}）`)
console.log(cloudEnvironment.adminApiUrl ? `后台与H5赛事接口：${cloudEnvironment.adminApiUrl}` : '后台HTTP访问地址待配置；已停用旧环境接口，小程序继续使用客户环境云函数。')
