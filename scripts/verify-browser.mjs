import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const base = process.env.PREVIEW_URL || 'http://127.0.0.1:5173/'
const out = 'artifacts/preview'
await fs.mkdir(out, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1, locale: 'zh-CN', timezoneId: 'Asia/Shanghai' })
const page = await context.newPage()
const errors = [], failedAssets = [], checks = []
page.on('pageerror', error => errors.push(error.message))
page.on('response', response => { if (response.status() >= 400 && response.url().startsWith(base)) failedAssets.push(`${response.status()} ${response.url()}`) })
const check = name => { checks.push(name); console.log(`PASS ${name}`) }
const nav = async name => { await page.locator('.desktop-nav .nav-item').filter({ hasText: name }).click() }
const shot = async name => { await page.screenshot({ path: `${out}/${name}.png`, fullPage: true }) }
const noOverflow = async p => { const dimensions = await p.evaluate(() => ({ viewport: window.innerWidth, page: document.documentElement.scrollWidth })); assert.ok(dimensions.page <= dimensions.viewport + 1, JSON.stringify(dimensions)) }
try {
  await page.goto(base, { waitUntil: 'networkidle' })
  await page.locator('.hero-title').waitFor()
  await shot('desktop-home')
  assert.equal(await page.locator('.home-matches .match-card').count(), 4)
  await noOverflow(page); check('desktop home loads four consistent fixtures without page overflow')
  await page.locator('.home-matches .match-card').first().click()
  await page.locator('.detail-scoreboard').waitFor()
  assert.match(await page.locator('.detail-score').innerText(), /2\s*:\s*1/)
  assert.equal(await page.locator('.timeline-event').count(), 3)
  await shot('desktop-match')
  check('home → match detail reconciles score and three goal events')
  await page.locator('.breadcrumb').click()
  await nav('赛事')
  await page.locator('.schedule-grid').waitFor()
  assert.equal(await page.locator('.schedule-grid .match-card').count(), 4)
  await page.locator('.filter-chip').filter({ hasText: /^进行中$/ }).click()
  assert.equal(await page.locator('.schedule-grid .match-card').count(), 1)
  assert.match(await page.locator('.schedule-grid').innerText(), /徐汇星火/)
  check('status filtering selects the simulated live fixture')
  await page.locator('[aria-label="选择2026-10-24"]').click()
  await page.getByText('这一天，球场休息一下', { exact: true }).waitFor()
  await page.getByText('回到演示比赛日', { exact: true }).click()
  assert.equal(await page.locator('.schedule-grid .match-card').count(), 4)
  check('rest day shows an empty state and reset restores all filters')
  await page.locator('.team-picker').click()
  await page.getByText('徐汇星火', { exact: true }).last().click()
  if (await page.getByText('确定', { exact: true }).isVisible()) await page.getByText('确定', { exact: true }).click()
  await page.waitForFunction(() => document.querySelectorAll('.schedule-grid .match-card').length === 1)
  assert.match(await page.locator('.schedule-grid').innerText(), /徐汇星火/)
  await page.locator('.team-picker').click()
  await page.getByText('全部球队', { exact: true }).last().click()
  if (await page.getByText('确定', { exact: true }).isVisible()) await page.getByText('确定', { exact: true }).click()
  await page.waitForFunction(() => document.querySelectorAll('.schedule-grid .match-card').length === 4)
  check('team picker changes and resets the schedule results')
  await shot('desktop-schedule')
  await page.locator('.page-tabs > uni-button').filter({ hasText: '对阵图' }).click()
  await page.locator('.bracket-tree').waitFor()
  assert.equal(await page.locator('.bracket-match').count(), 7)
  assert.match(await page.locator('.semis .bracket-match').first().innerText(), /江湾联队/)
  assert.match(await page.locator('.semis .bracket-match').first().innerText(), /Q2 胜者/)
  await shot('desktop-bracket')
  await page.locator('.final .bracket-match').click()
  await page.locator('.detail-vs').waitFor()
  assert.equal(await page.locator('.timeline-event').count(), 0)
  assert.match(await page.locator('.detail-stat-panel').innerText(), /比赛尚未开始/)
  check('bracket has seven clickable fixtures and pending final does not fabricate scores')
  await page.locator('.breadcrumb').click()
  await nav('动态')
  await page.locator('.category-filters .filter-chip').filter({ hasText: /^公告$/ }).click()
  assert.equal(await page.locator('.news-item').count(), 1)
  await page.locator('.news-item').click()
  await page.locator('.article-title').waitFor()
  assert.match(await page.locator('.article-notice').innerText(), /演示公告/)
  await page.locator('.breadcrumb').click()
  check('news category filter and full article reading work')
  await nav('数据')
  assert.equal(await page.locator('.stats-panel').count(), 2)
  await page.locator('.stats-tabs > uni-button').filter({ hasText: '射手榜' }).click()
  assert.ok(await page.locator('.player-rank-row:not(.table-header)').count() > 0)
  await shot('desktop-stats')
  check('standings and scorer tabs render calculated data')
  await nav('赛事')
  await page.locator('.page-tabs > uni-button').filter({ hasText: '参赛球队' }).click()
  await page.locator('.team-card').first().locator('.follow-button').click()
  await nav('我的')
  assert.equal(await page.locator('.favorite-row').count(), 1)
  await page.reload({ waitUntil: 'networkidle' })
  await nav('我的')
  assert.equal(await page.locator('.favorite-row').count(), 1)
  await page.locator('.favorite-row .follow-button').click()
  assert.equal(await page.locator('.favorite-row').count(), 0)
  check('follow/unfollow persists locally across reload without server requests')
  await page.locator('.search-trigger').focus()
  await page.keyboard.press('Enter')
  await page.locator('.search-panel').waitFor()
  await page.keyboard.press('Escape')
  await page.locator('.search-panel').waitFor({ state: 'detached' })
  check('keyboard can open and dismiss the search dialog')
  await page.locator('.search-trigger').click()
  await page.locator('.search-input input').fill('不存在的球队XYZ')
  await page.getByText('试试球队名称或场地名称', { exact: true }).waitFor()
  await page.locator('.search-input input').fill('江湾联队')
  await page.locator('.search-result').first().waitFor(); assert.ok(await page.locator('.search-result').count() > 0)
  await page.locator('.search-result').first().click()
  await page.locator('.team-detail-header').waitFor()
  assert.match(await page.locator('.team-detail-header').innerText(), /江湾联队/)
  await shot('desktop-team')
  check('search supports empty results, ranked team results, and navigation')
  await page.goto(`${base}#/pages/match/detail?id=missing`, { waitUntil: 'networkidle' })
  await page.getByText('没有找到这场比赛', { exact: true }).waitFor()
  check('unknown match route fails gracefully')
  for (const width of [390, 320, 768]) {
    const mobile = await browser.newContext({ viewport: { width, height: 844 }, deviceScaleFactor: 1, locale: 'zh-CN', timezoneId: 'Asia/Shanghai', isMobile: width < 760, hasTouch: true })
    const p = await mobile.newPage()
    p.on('pageerror', error => errors.push(error.message))
    await p.goto(base, { waitUntil: 'networkidle' }); await p.locator('.hero-title').waitFor()
    await noOverflow(p)
    await p.screenshot({ path: `${out}/home-${width}.png`, fullPage: true }); if (width === 390) await p.screenshot({ path: `${out}/mobile-home.png`, fullPage: false })
    const navSelector = width < 760 ? '.mobile-nav-item' : '.desktop-nav .nav-item'
    await p.locator(navSelector).filter({ hasText: /^赛事$/ }).click()
    await p.locator('.schedule-grid').waitFor(); await noOverflow(p)
    await p.screenshot({ path: `${out}/schedule-${width}.png`, fullPage: true })
    await p.locator('.page-tabs > uni-button').filter({ hasText: '对阵图' }).click()
    await p.locator('.bracket-tree').waitFor(); await noOverflow(p)
    await p.screenshot({ path: `${out}/bracket-${width}.png`, fullPage: true }); if (width === 390) await p.screenshot({ path: `${out}/mobile-bracket.png`, fullPage: false })
    if (width < 760) {
      const scrolled = await p.locator('.bracket-scroll').evaluate(root => {
        const container = [...root.querySelectorAll('*')].find(element => element.scrollWidth > element.clientWidth && ['auto', 'scroll'].includes(getComputedStyle(element).overflowX))
        if (!container) return false
        container.scrollLeft = container.scrollWidth
        return container.scrollLeft > 0
      })
      assert.ok(scrolled, 'bracket supports its own horizontal scroll')
      if (width === 390) await p.screenshot({ path: `${out}/mobile-bracket-final.png`, fullPage: false })
      await noOverflow(p)
    }
    if (width === 390) {
      await p.locator('.quarters .bracket-match').first().click()
      await p.locator('.detail-scoreboard').waitFor(); await noOverflow(p)
      await p.screenshot({ path: `${out}/match-${width}.png`, fullPage: true })
    }
    check(`${width}px home, schedule, bracket, and local scrolling avoid horizontal page overflow`)
    await mobile.close()
  }
  assert.deepEqual(errors, [], 'uncaught browser exceptions')
  assert.deepEqual(failedAssets, [], 'missing local assets')
  await fs.writeFile(`${out}/report.json`, JSON.stringify({ checks, errors, failedAssets, browser: await browser.version(), generatedAt: new Date().toISOString() }, null, 2))
  console.log(`Verified ${checks.length} flows. Screenshots: ${out}`)
} catch (error) {
  await shot('failure')
  await fs.writeFile(`${out}/failure-dom.txt`, await page.locator('body').innerText())
  console.error('Browser errors:', errors, 'Missing assets:', failedAssets)
  throw error
} finally {
  const shutdown = setTimeout(() => { console.error('Browser cleanup timed out'); process.exit(1) }, 10000)
  shutdown.unref()
  await browser.close()
  clearTimeout(shutdown)
}
